#include "hc595.h"

//配置与HC595相连的I/O口
void HC595_Port_Init(void)
{
	P3M1 &= ~0x34; P3M0 |= 0x34; //P32、P34、P35设置为推挽输出
	
	P32 = 0; 	//移位时钟低电平
	P35 = 0;	//锁存时钟低电平
				//HC595不会接收和发送数据
}

//将数据Dat按位发送给HC595
void HC595_SendByte(uint8_t dat)
{
	uint8_t i; 					//定义遍历符号	
	P35 = 0;					//保证进入移位前锁存时钟是低电平，防范干扰
	
	for(i = 0; i < 8; i++) 		//主机发送八位数据
	{		
		P34 = ( dat & 0x80 );	//主机从最高位开始发送		
		dat <<= 1;				//dat左移一位

		P32 = 0;				//先确保是低电平
		_nop_();		
		P32 = 1;				//产生上升沿
		_nop_();				
		P32 = 0;				//拉回低电平，准备下一次		
		P35 = 0;				//每移一位都强行拉低一次，防范干扰
	}
}

//命令HC595输出数据
void HC595_Latch(void)
{
	P35 = 0;	//先确保是低电平
	_nop_();
	P35 = 1;	//产生上升沿
	_nop_();				
	P35 = 0;	//拉回低电平，准备下一次
}
